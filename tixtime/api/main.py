@app.get("/api/events/{event_id}")
def event_detail(event_id: int, con=Depends(get_connection), as_of: date = Depends(resolve_as_of)):
    rows = con.execute(
        """
        SELECT e.*, v.venue_name, v.city, v.region, v.archetype, v.capacity
        FROM events e JOIN venues v USING (venue_id) WHERE e.event_id = ?
        """,
        [event_id],
    ).df()
    if rows.empty:
        raise HTTPException(404, f"event {event_id} not found")
    row = rows.to_dict("records")[0]

    board = con.execute(
        """
        SELECT d.*, t.label AS tier_label, t.tier_rank
        FROM deal_board d
        LEFT JOIN seat_tiers t ON t.tier_key = d.tier_key
             AND t.archetype = (SELECT archetype FROM venues WHERE venue_id = ?)
        WHERE d.event_id = ? AND d.as_of_date = ? ORDER BY t.tier_rank NULLS LAST
        """,
        [row["venue_id"], event_id, as_of],
    ).df()
    board = _records(board)

    forecastable, reason = _forecastability(
        {**row, "price_now": board[0]["price_now"] if board else None},
        board_current=board_as_of(con) == as_of,
    )
    # row comes straight from a DataFrame here, so event_date is a Timestamp;
    # comparing it to a date raises rather than coercing.
    event_day = row["event_date"]
    if event_day is not None and hasattr(event_day, "date"):
        event_day = event_day.date()
    if event_day and event_day <= as_of:
        forecastable, reason = False, "past_event"

    return {
        **_provenance(as_of, con),
        "event": {
            "event_id": row["event_id"],
            "name": row["name"],
            "league": row["league"],
            "event_type": row["event_type"],
            "event_date": _iso(row["event_date"]),
            "event_datetime_utc": (
                row["event_datetime_utc"].isoformat() if row["event_datetime_utc"] else None
            ),
            "home_team": row["home_team"],
            "away_team": row["away_team"],
            "postseason_tier": row["postseason_tier"],
            "venue_name": row["venue_name"],
            "city": row["city"],
            "region": row["region"],
            "capacity": row["capacity"],
            "is_ga": bool(row["is_ga"]),
            # These two real columns decide whether a seat switcher is even
            # meaningful. A GA event has no sections; showing a tier picker for
            # one is a factual error a user catches in a single click.
            "seat_selection": bool(row["seat_selection"]),
            "has_seat_tiers": bool(row["seat_selection"]) and not bool(row["is_ga"]),
            "is_forecastable": forecastable,
            "unforecastable_reason": reason,
            "purchase_url": row["url"],
            "announce_date": _iso(row["announce_date"]),
        },
        "tiers": [
            {
                **{k: (v.isoformat() if isinstance(v, date) else v) for k, v in tier.items()},
                "tier_label": tier.get("tier_label") or tier["tier_key"],
            }
            for tier in board
        ],
    }


@app.get("/api/events/{event_id}/timeline")
def timeline(
    event_id: int,
    tier_key: str | None = None,
    con=Depends(get_connection),
    as_of: date = Depends(resolve_as_of),
):
    """History + forecast + recommendation in ONE call.

    The hero chart needs all three on a single date axis. Splitting them across
    endpoints invites the client to stitch series that were computed against
    different as-of dates, which would silently misalign the chart.
    """
    event = con.execute(
        "SELECT e.*, v.archetype FROM events e JOIN venues v USING (venue_id) WHERE e.event_id = ?",
        [event_id],
    ).df()
    if event.empty:
        raise HTTPException(404, f"event {event_id} not found")
    event_row = event.to_dict("records")[0]

    if tier_key is None:
        picked = con.execute(
            "SELECT tier_key FROM deal_board WHERE event_id = ? AND as_of_date = ? "
            "ORDER BY expected_saving_pct DESC LIMIT 1",
            [event_id, as_of],
        ).fetchone()
        # The board only covers one date. Falling back to the snapshots keeps
        # the price chart rendering at any clock date -- history and forecast
        # are computed live and stay correct even when the ranked board does
        # not cover the date.
        if picked is None:
            picked = con.execute(
                "SELECT tier_key FROM price_snapshots WHERE event_id = ? AND NOT is_burn_in "
                "GROUP BY tier_key ORDER BY min(get_in_price) LIMIT 1",
                [event_id],
            ).fetchone()
        tier_key = picked[0] if picked else None
    if tier_key is None:
        return {**_provenance(as_of), "event_id": event_id, "tier_key": None,
                "history": [], "forecast": [], "recommendation": None,
                "unforecastable_reason": "no_snapshots"}

    history = con.execute(
        """
        SELECT as_of_date, days_until_event, get_in_price, median_price, listing_count
        FROM price_snapshots
        WHERE event_id = ? AND tier_key = ? AND NOT is_burn_in AND as_of_date <= ?
        ORDER BY as_of_date
        """,
        [event_id, tier_key, as_of],
    ).df()

    forecast = serve.forecast_curve(con, event_id, tier_key, as_of)
    recommendation = serve.recommend(con, event_id, tier_key, as_of)

    return {
        **_provenance(as_of),
        "event_id": event_id,
        "tier_key": tier_key,
        "history": [
            {
                "date": _iso(r["as_of_date"]),
                "days_until_event": int(r["days_until_event"]),
                "get_in_price": round(float(r["get_in_price"]), 2),
                "median_price": round(float(r["median_price"]), 2),
                "listing_count": int(r["listing_count"]),
            }
            for r in _records(history)
        ],
        "forecast": [
            {"date": p.as_of_date, "days_until_event": p.days_until_event,
             "horizon_days": p.horizon_days, "q10": p.q10, "q50": p.q50, "q90": p.q90}
            for p in forecast
        ],
        "recommendation": recommendation.__dict__,
    }


