@app.get("/api/venues")
def venues(con=Depends(get_connection), as_of: date = Depends(resolve_as_of),
           q: str | None = None, limit: int = Query(200, le=500)):
    clause, params = "", [as_of]
    if q:
        clause = "AND (lower(v.venue_name) LIKE ? OR lower(v.city) LIKE ?)"
        params += [f"%{q.lower()}%"] * 2
    rows = con.execute(
        f"""
        SELECT v.venue_id, v.venue_name, v.city, v.region, v.archetype, v.capacity,
               count(e.event_id) FILTER (WHERE e.event_date > ?) AS upcoming_events,
               v.event_count AS total_events
        FROM venues v LEFT JOIN events e USING (venue_id)
        WHERE 1=1 {clause}
        GROUP BY 1,2,3,4,5,6,8 ORDER BY upcoming_events DESC, v.venue_name LIMIT {int(limit)}
        """,
        params,
    ).df()
    return {**_provenance(as_of), "venues": _records(rows)}


@app.get("/api/teams")
def teams(con=Depends(get_connection), as_of: date = Depends(resolve_as_of),
          q: str | None = None, limit: int = Query(200, le=500)):
    clause, params = "", [as_of]
    if q:
        clause = "AND lower(e.home_team) LIKE ?"
        params.append(f"%{q.lower()}%")
    rows = con.execute(
        f"""
        SELECT e.home_slug AS slug, e.home_team AS name, e.league,
               count(*) FILTER (WHERE e.event_date > ?) AS upcoming_events,
               min(v.venue_name) AS home_venue
        FROM events e JOIN venues v USING (venue_id)
        WHERE e.home_team IS NOT NULL {clause}
        GROUP BY 1,2,3 HAVING upcoming_events > 0
        ORDER BY upcoming_events DESC LIMIT {int(limit)}
        """,
        params,
    ).df()
    return {**_provenance(as_of), "teams": _records(rows)}


@app.get("/api/accuracy")
def accuracy(as_of: date = Depends(resolve_as_of)):
    """Backtest and training metrics, with the caveat attached to the numbers."""
    payload: dict[str, Any] = {**_provenance(as_of)}
    for name, filename in (("backtest", "backtest.json"), ("training", "training_metrics.json")):
        path = REPORT_DIR / filename
        payload[name] = json.loads(path.read_text()) if path.exists() else None
    payload["interpretation"] = (
        "These figures are measured on simulated prices. They demonstrate that the "
        "pipeline recovers timing structure it was not trained on -- the backtest scores "
        "events the model never saw -- but they are NOT evidence that the model would "
        "predict real ticket prices well. Connect a live price collector to measure that."
    )
    return payload


