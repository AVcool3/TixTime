def get_connection():
    con = db.connect(read_only=False)
    try:
        yield con
    finally:
        con.close()


def resolve_as_of(as_of: date | None = Query(default=None)) -> date:
    return as_of or as_of_date()


def _records(frame) -> list[dict]:
    """DataFrame -> JSON-safe records.

    DuckDB returns NaN for SQL NULL in numeric columns and numpy scalars
    everywhere; json.dumps rejects both ("Out of range float values are not
    JSON compliant"). Every DataFrame leaving this module goes through here.
    """
    import numpy as np
    import pandas as pd

    if frame is None or len(frame) == 0:
        return []
    cleaned = frame.replace({np.nan: None, np.inf: None, -np.inf: None})
    records = cleaned.to_dict("records")
    out = []
    for record in records:
        row = {}
        for key, value in record.items():
            if value is None or (isinstance(value, float) and value != value):
                row[key] = None
            elif isinstance(value, (np.integer,)):
                row[key] = int(value)
            elif isinstance(value, (np.floating,)):
                row[key] = None if np.isnan(value) else float(value)
            elif isinstance(value, (np.bool_,)):
                row[key] = bool(value)
            elif isinstance(value, pd.Timestamp):
                # DuckDB DATE columns arrive as midnight Timestamps. Emitting
                # them with a time component makes the same logical date
                # compare unequal to a plain "YYYY-MM-DD" from another
                # endpoint, so dates stay date-shaped.
                row[key] = (
                    value.date().isoformat()
                    if (value.hour, value.minute, value.second, value.microsecond) == (0, 0, 0, 0)
                    else value.isoformat()
                )
            elif isinstance(value, date):
                row[key] = value.isoformat()
            else:
                row[key] = value
        out.append(row)
    return out


def _iso(value) -> str | None:
    """Dates may already be isoformat strings by the time they reach here,
    because _records normalises them. Accept either."""
    if value is None:
        return None
    return value.isoformat() if hasattr(value, "isoformat") else str(value)


def board_as_of(con) -> date | None:
    """The single as-of date the precomputed deal board was built for."""
    row = con.execute("SELECT max(as_of_date) FROM deal_board").fetchone()
    return row[0] if row and row[0] else None


def _provenance(as_of: date, con=None) -> dict[str, Any]:
    payload = {
        "as_of": as_of.isoformat(),
        "source": SYNTHETIC_SOURCE,
        "is_simulated": True,
        "disclaimer": DISCLAIMER,
    }
    if con is not None:
        # The deal board and sparklines are precomputed for ONE date. Serving
        # them for a different as_of would hand back predictions derived from
        # prices after the date the response claims -- and the clock control
        # actively invites moving the clock. So the board is filtered to its
        # own date, and the response says plainly when it does not cover the
        # requested one.
        built = board_as_of(con)
        payload["board_as_of"] = built.isoformat() if built else None
        payload["board_covers_as_of"] = built == as_of
        if built != as_of:
            payload["board_note"] = (
                f"The ranked deal board was built for {built}. Rankings, sparklines and "
                f"buy signals are unavailable for {as_of}; per-event forecasts on the event "
                f"page are still computed live and remain correct. Rebuild with "
                f"`python -m tixtime.ml.precompute --as-of {as_of}`."
            )
    return payload


