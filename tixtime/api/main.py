"""TixTime HTTP API.

Two contracts run through every endpoint here:

AS-OF. Nothing means "now". Every price-bearing endpoint takes an `as_of`
query parameter defaulting to the configured clock, and never reads a snapshot
dated after it. The warehouse physically contains the whole future path (the
simulator generated it), so this is the boundary that stops the site from
reading answers out of the back of the book.

PROVENANCE. Every response carrying a price carries `source` and
`is_simulated` alongside it. A column in the database is invisible at the
surface where harm happens and is dropped by the first aggregation; the flag
travels with the number instead.
"""

