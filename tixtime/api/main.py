class AlertRuleIn(BaseModel):
    event_id: int
    rule_type: str = Field(description="model_buy | target_price | drop_pct")
    tier_key: str | None = None
    threshold: float | None = None
    channel: str = "inapp"
    destination: str | None = None
    label: str | None = None


@app.post("/api/alerts/rules", status_code=201)
def create_alert_rule(payload: AlertRuleIn, con=Depends(get_connection)):
    try:
        rule_id = alerts.create_rule(
            con, payload.event_id, payload.rule_type, payload.tier_key,
            payload.threshold, payload.channel, payload.destination, payload.label,
        )
    except ValueError as exc:
        raise HTTPException(400, str(exc)) from exc
    return {"rule_id": rule_id}


