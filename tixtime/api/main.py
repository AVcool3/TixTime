@app.get("/api/meta")
def meta(con=Depends(get_connection), as_of: date = Depends(resolve_as_of)):
    counts = con.execute(
        """
        SELECT
          (SELECT count(*) FROM events)                                AS events,
          (SELECT count(*) FROM events WHERE is_modelable)             AS modelable,
          (SELECT count(*) FROM events WHERE event_date > ? AND is_modelable) AS upcoming,
          (SELECT count(*) FROM venues)                                AS venues,
          (SELECT count(*) FROM franchises WHERE event_count > 0)      AS teams,
          (SELECT count(*) FROM price_snapshots)                       AS snapshots
        """,
        [as_of],
    ).fetchone()
    # Restricted to modelable events on purpose: the export carries nine rows
    # with corrupt dates out in 2056, and letting them define the catalogue
    # window would push the clock control's range 30 years past the data.
    window = con.execute(
        "SELECT min(event_date), max(event_date) FROM events WHERE is_modelable"
    ).fetchone()
    model_version = con.execute(
        "SELECT detail FROM pipeline_runs WHERE stage='train' ORDER BY ran_at DESC LIMIT 1"
    ).fetchone()
    return {
        **_provenance(as_of, con),
        "catalogue": {
            "events": counts[0],
            "modelable_events": counts[1],
            "upcoming_events": counts[2],
            "venues": counts[3],
            "teams": counts[4],
            "price_snapshots": counts[5],
            "catalogue_start": window[0].isoformat() if window[0] else None,
            "catalogue_end": window[1].isoformat() if window[1] else None,
        },
        "model_version": model_version[0] if model_version else None,
        "clock_note": (
            "The catalogue runs to "
            f"{window[1].isoformat() if window[1] else 'mid-2026'}, which real-world today has "
            "passed. TixTime therefore runs on an explicit as-of date: events before it are "
            "history used for training and backtesting, events after it are what the site "
            "recommends on. Move the clock to replay any date."
        ),
    }


@app.get("/api/filters")
def filters(con=Depends(get_connection), as_of: date = Depends(resolve_as_of)):
    """Facet values with counts, so the filter rail is populated not empty."""

    def facet(sql: str) -> list[dict]:
        return [
            {"value": row[0], "label": row[1], "count": row[2]}
            for row in con.execute(sql, [as_of]).fetchall()
            if row[0] is not None
        ]

    return {
        **_provenance(as_of, con),
        "leagues": facet(
            "SELECT league, upper(league), count(*) FROM events "
            "WHERE event_date > ? AND league IS NOT NULL GROUP BY 1,2 ORDER BY 3 DESC"
        ),
        "cities": facet(
            "SELECT v.city, v.city || ', ' || v.region, count(*) FROM events e "
            "JOIN venues v USING (venue_id) WHERE e.event_date > ? AND v.city IS NOT NULL "
            "GROUP BY 1,2 ORDER BY 3 DESC LIMIT 60"
        ),
        "venues": facet(
            "SELECT CAST(v.venue_id AS VARCHAR), v.venue_name, count(*) FROM events e "
            "JOIN venues v USING (venue_id) WHERE e.event_date > ? GROUP BY 1,2 ORDER BY 3 DESC LIMIT 80"
        ),
        "teams": facet(
            "SELECT e.home_slug, e.home_team, count(*) FROM events e "
            "WHERE e.event_date > ? AND e.home_team IS NOT NULL GROUP BY 1,2 ORDER BY 3 DESC LIMIT 120"
        ),
        "postseason_tiers": facet(
            "SELECT postseason_tier, replace(postseason_tier,'_',' '), count(*) FROM events "
            "WHERE event_date > ? GROUP BY 1,2 ORDER BY 3 DESC"
        ),
    }


