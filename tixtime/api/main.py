DISCLAIMER = (
    "Prices are simulated. The SeatGeek export this catalogue is built from has every "
    "price column redacted, and no ticket API is reachable from this deployment, so the "
    "price history and every figure derived from it are generated by TixTime's market "
    "simulator. Event names, dates, venues and purchase links are real."
)

