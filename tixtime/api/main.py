_SEARCH_SQL = """
SELECT e.event_id, e.name, e.short_name, e.league, e.event_date, e.event_datetime_utc,
       e.home_team, e.away_team, e.postseason_tier, e.is_ga, e.seat_selection,
       e.is_tbd, e.is_modelable, e.exclusion_reason, e.url,
       v.venue_name, v.city, v.region, v.archetype,
       d.tier_key, d.price_now, d.forecast_min, d.forecast_min_date,
       d.days_to_forecast_min, d.expected_saving, d.expected_saving_pct,
       d.action, d.confidence, d.days_until_event,
       s.points AS sparkline
FROM events e
JOIN venues v USING (venue_id)
LEFT JOIN (
    SELECT * FROM deal_board
    WHERE as_of_date = ?
    QUALIFY row_number() OVER (PARTITION BY event_id ORDER BY expected_saving_pct DESC) = 1
) d ON d.event_id = e.event_id
LEFT JOIN event_sparkline s ON s.event_id = e.event_id AND s.tier_key = d.tier_key
WHERE e.event_date > ?
"""


def _event_row(row: dict, as_of: date, board_current: bool = True) -> dict:
    forecastable, reason = _forecastability(row, board_current)
    return {
        "event_id": row["event_id"],
        "name": row["name"],
        "short_name": row["short_name"],
        "league": row["league"],
        "event_date": _iso(row["event_date"]),
        "home_team": row["home_team"],
        "away_team": row["away_team"],
        "postseason_tier": row["postseason_tier"],
        "venue_name": row["venue_name"],
        "city": row["city"],
        "region": row["region"],
        "is_ga": bool(row["is_ga"]),
        "seat_selection": bool(row["seat_selection"]),
        "is_forecastable": forecastable,
        "unforecastable_reason": reason,
        "purchase_url": row["url"],
        "days_until_event": row.get("days_until_event"),
        "best_tier": row.get("tier_key"),
        "price_now": row.get("price_now"),
        "forecast_min": row.get("forecast_min"),
        "forecast_min_date": _iso(row.get("forecast_min_date")),
        "days_to_forecast_min": row.get("days_to_forecast_min"),
        "expected_saving": row.get("expected_saving"),
        "expected_saving_pct": row.get("expected_saving_pct"),
        "action": row.get("action"),
        "confidence": row.get("confidence"),
        "sparkline": json.loads(row["sparkline"]) if row.get("sparkline") else None,
        "source": SYNTHETIC_SOURCE,
        "is_simulated": True,
    }


def _forecastability(row: dict, board_current: bool = True) -> tuple[bool, str | None]:
    """Why an event has no forecast, stated rather than rendered as a blank chart."""
    if row.get("is_tbd"):
        return False, "date_tbd"
    if not row.get("is_modelable"):
        return False, row.get("exclusion_reason") or "not_modelable"
    if row.get("price_now") is None:
        # Distinguish "this event genuinely has no price history" from "the
        # ranked board simply was not built for this clock date". Conflating
        # them told the user no observations existed while the chart below
        # drew a hundred of them.
        return False, "no_snapshots" if board_current else "board_not_built"
    return True, None


@app.get("/api/search")
def search(
    con=Depends(get_connection),
    as_of: date = Depends(resolve_as_of),
    q: str | None = None,
    league: str | None = None,
    city: str | None = None,
    venue_id: int | None = None,
    team: str | None = None,
    postseason_tier: str | None = None,
    date_from: date | None = None,
    date_to: date | None = None,
    max_price: float | None = None,
    action: str | None = None,
    # Default to events that can actually be forecast. The catalogue contains
    # 1,316 stadium tours and other non-game inventory which sort to the front
    # by date and would otherwise fill the entire first page with rows reading
    # "No forecast" -- the product's worst possible first impression.
    include_unforecastable: bool = False,
    sort: str = Query("date", pattern="^(date|saving|price|name)$"),
    limit: int = Query(60, le=200),
    offset: int = 0,
):
    # First param feeds the deal_board subquery, second the event_date filter.
    clauses, params = [], [as_of, as_of]
    # When the board does not cover this date there are no predictions to
    # filter on, so fall back to the catalogue rather than returning nothing:
    # the events are still browsable and their per-event forecasts are still
    # computed live and correct.
    board_current = board_as_of(con) == as_of
    if not include_unforecastable and board_current:
        clauses.append("e.is_modelable AND d.price_now IS NOT NULL")
    elif not include_unforecastable:
        clauses.append("e.is_modelable")
    if q:
        clauses.append(
            "(lower(e.name) LIKE ? OR lower(v.venue_name) LIKE ? OR lower(v.city) LIKE ?)"
        )
        params += [f"%{q.lower()}%"] * 3
    if league:
        clauses.append("e.league = ?"); params.append(league)
    if city:
        clauses.append("v.city = ?"); params.append(city)
    if venue_id:
        clauses.append("e.venue_id = ?"); params.append(venue_id)
    if team:
        clauses.append("(e.home_slug = ? OR lower(e.away_team) = ?)")
        params += [team, team.replace("-", " ").lower()]
    if postseason_tier:
        clauses.append("e.postseason_tier = ?"); params.append(postseason_tier)
    if date_from:
        clauses.append("e.event_date >= ?"); params.append(date_from)
    if date_to:
        clauses.append("e.event_date <= ?"); params.append(date_to)
    if max_price is not None:
        clauses.append("d.price_now <= ?"); params.append(max_price)
    if action:
        clauses.append("d.action = ?"); params.append(action)

    where = (" AND " + " AND ".join(clauses)) if clauses else ""
    order = {
        "date": "e.event_date ASC, e.event_id ASC",
        "saving": "d.expected_saving_pct DESC NULLS LAST, e.event_date ASC",
        "price": "d.price_now ASC NULLS LAST",
        "name": "e.name ASC",
    }[sort]

    total = con.execute(
        f"SELECT count(*) FROM ({_SEARCH_SQL}{where}) t", params
    ).fetchone()[0]
    rows = _records(con.execute(
        f"{_SEARCH_SQL}{where} ORDER BY {order} LIMIT {int(limit)} OFFSET {int(offset)}", params
    ).df())

    return {
        **_provenance(as_of, con),
        "total": total,
        "limit": limit,
        "offset": offset,
        "results": [_event_row(row, as_of, board_current) for row in rows],
    }


@app.get("/api/deals")
def deals(
    con=Depends(get_connection),
    as_of: date = Depends(resolve_as_of),
    league: str | None = None,
    city: str | None = None,
    venue_id: int | None = None,
    team: str | None = None,
    tier_key: str | None = None,
    date_from: date | None = None,
    date_to: date | None = None,
    max_price: float | None = None,
    min_saving_pct: float = 0.0,
    limit: int = Query(80, le=300),
    offset: int = 0,
):
    """Cross-event ranked board: where is waiting worth the most, right now?

    This is the question the product exists to answer, and it is a comparison
    across events, not a per-event lookup -- so it is served from the
    precomputed deal_board rather than by fanning out model calls.
    """
    clauses = ["e.event_date > ?", "d.expected_saving_pct >= ?", "d.as_of_date = ?"]
    params: list = [as_of, min_saving_pct, as_of]
    if league:
        clauses.append("e.league = ?"); params.append(league)
    if city:
        clauses.append("v.city = ?"); params.append(city)
    if venue_id:
        clauses.append("e.venue_id = ?"); params.append(venue_id)
    if team:
        clauses.append("e.home_slug = ?"); params.append(team)
    if tier_key:
        clauses.append("d.tier_key = ?"); params.append(tier_key)
    if date_from:
        clauses.append("e.event_date >= ?"); params.append(date_from)
    if date_to:
        clauses.append("e.event_date <= ?"); params.append(date_to)
    if max_price is not None:
        clauses.append("d.price_now <= ?"); params.append(max_price)

    where = " AND ".join(clauses)
    sql = f"""
        SELECT e.event_id, e.name, e.league, e.event_date, e.home_team, e.away_team,
               e.postseason_tier, e.is_ga, e.url, v.venue_name, v.city, v.region,
               d.tier_key, t.label AS tier_label, d.price_now, d.forecast_min,
               d.forecast_min_date, d.days_to_forecast_min, d.expected_saving,
               d.expected_saving_pct, d.action, d.confidence, d.days_until_event
        FROM deal_board d
        JOIN events e USING (event_id)
        JOIN venues v USING (venue_id)
        LEFT JOIN seat_tiers t ON t.tier_key = d.tier_key AND t.archetype = v.archetype
        WHERE {where}
    """
    total = con.execute(f"SELECT count(*) FROM ({sql}) x", params).fetchone()[0]
    rows = con.execute(
        f"{sql} ORDER BY d.expected_saving_pct DESC, d.expected_saving DESC "
        f"LIMIT {int(limit)} OFFSET {int(offset)}",
        params,
    ).df()

    records = []
    for row in _records(rows):
        records.append(
            {
                **{
                    k: (v.isoformat() if isinstance(v, date) else v)
                    for k, v in row.items()
                },
                "tier_label": row.get("tier_label") or row["tier_key"],
                "source": SYNTHETIC_SOURCE,
                "is_simulated": True,
            }
        )
    return {**_provenance(as_of, con), "total": total, "limit": limit, "offset": offset, "deals": records}


